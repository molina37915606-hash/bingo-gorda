'use strict';
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'transmision.html'),'utf8');
const js=fs.readFileSync(path.join(root,'js','transmision.js'),'utf8');
const tv=fs.readFileSync(path.join(root,'tv.html'),'utf8');
const must=(ok,msg)=>{if(!ok){console.error('TRANSMISION MOBILE FAIL:',msg);process.exit(1)}};
must(html.includes('id="orientationGate"')&&html.includes('GIRÁ EL CELULAR'),'Vertical debe mostrar aviso de rotación');
must(html.includes('@media(max-width:900px) and (orientation:portrait){.orientationGate{display:grid}}'),'El aviso debe limitarse a móvil vertical');
must(html.includes('@media(max-width:1000px) and (max-height:600px) and (orientation:landscape)'),'Debe existir layout específico de celular horizontal');
must(html.includes('.drawTicker{display:grid!important;grid-column:4!important'),'Horizontal debe conservar el panel de premio confirmado');
must(html.includes('.cards.mode90Cards>.featured:nth-child(n+2){display:grid!important}'),'Bingo 90 horizontal debe recuperar los 6 cartones');
must(html.includes('.cards.mode75Cards>.featured:nth-child(n+2){display:grid!important}'),'Bingo 75 horizontal debe recuperar la carrera completa');
must(html.includes('grid-template-columns:minmax(0,1fr) clamp(145px,24vw,205px)!important'),'Horizontal debe conservar chat lateral');
must(html.includes('.presenter{display:grid!important'),'Horizontal debe conservar a Vero');
must(js.includes("screen.orientation?.lock?.('landscape')")&&js.includes('screen.orientation?.unlock?.()'),'Pantalla completa debe intentar bloquear horizontal sin depender de soporte');
must(js.includes("$('orientationFullBtn')?.addEventListener('click'"),'El aviso vertical debe ofrecer pantalla completa');
must(!tv.includes('orientationGate'),'TV no debe recibir el bloqueo móvil de Transmisión');
console.log('PRUEBA TRANSMISION MOBILE HORIZONTAL COMPLETA: OK');
