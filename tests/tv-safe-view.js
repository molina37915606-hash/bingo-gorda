const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'tv.html'),'utf8');
const js=fs.readFileSync(path.join(root,'js','tv.js'),'utf8');
const server=fs.readFileSync(path.join(root,'server.js'),'utf8');
const community=fs.readFileSync(path.join(root,'js','community.js'),'utf8');
const admin=fs.readFileSync(path.join(root,'js','admin.js'),'utf8');
const must=(ok,msg)=>{if(!ok){console.error('TV SAFE FAIL:',msg);process.exit(1)}};
must(server.includes("path.join(ROOT, 'tv.html')"),'tv.html debe estar permitido por serveFile');
must(server.includes("url.pathname === '/tv'")&&server.includes("/^\\/tv\\/[^/]+\\/?$/"),'deben existir /tv y /tv/:codigo');
must(server.includes('randomNumericCode(6)'),'nuevas salas deben usar codigo TV numerico corto');
must(html.includes('MODO TV')&&html.includes('CARTONES MÁS CERCA')&&html.includes('CHAT DE LA SALA'),'TV debe conservar bolilla, carrera y chat');
must(html.includes('raceGrid mode90')&&html.includes('.raceGrid{min-height:0;display:grid;grid-template-columns:repeat(3'),'TV debe reservar seis cartones grandes 3x2');
must(!html.includes('id="prizePanel"')&&html.includes('id="playingFor"'),'TV simple debe liberar el panel fijo y mostrar que se juega');
must(js.includes('pendingRaw=raw')&&js.includes('setTimeout(flushPending,45)'),'TV debe coalescer estados y saltar a la informacion mas nueva');
must(js.includes('Date.now()-lastStateAt>8000')&&js.includes("document.visibilityState==='visible'"),'TV debe resincronizar tras atraso o volver a primer plano');
must(js.includes("slice(-3)")&&js.includes('renderChat'),'TV debe limitar el chat compacto visible');
must(js.includes('raceHotNumbers')&&html.includes('hotTarget'),'TV debe resaltar números faltantes calientes');
must(js.includes("s.status==='finished'&&(s.finalShowcase||[]).length>0"),'TV debe mostrar cartones ganadores al finalizar');
must(html.includes('/js/bingo-voice.js')&&js.includes('window.BingoVoice')&&js.includes('playBall'),'TV debe usar la biblioteca local compartida de La Gorda');
must(!js.includes('speechSynthesis')&&!js.includes('SpeechSynthesisUtterance'),'TV no debe depender de la voz sintetizada del dispositivo');
must(!community.includes('MODO TV')&&community.includes('VER TRANSMISIÓN'),'Comunidad debe priorizar la Transmisión completa y no mostrar Modo TV');
must(admin.includes('openTvTransmission'),'Admin debe poder abrir Modo TV');
console.log('PRUEBA MODO TV SAFE: OK');
