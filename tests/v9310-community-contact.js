const fs=require('fs');
const path=require('path');
function assert(ok,msg){if(!ok){console.error('FAIL:',msg);process.exit(1)}}
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'comunidad.html'),'utf8');
const community=fs.readFileSync(path.join(root,'js','community.js'),'utf8');
const adminHtml=fs.readFileSync(path.join(root,'admin.html'),'utf8');
const admin=fs.readFileSync(path.join(root,'js','admin.js'),'utf8');
const server=fs.readFileSync(path.join(root,'server.js'),'utf8');
assert(html.includes('id="mobileContactBtn"')&&html.includes('CONTACTANOS'),'Móvil debe tener CONTACTANOS en cabecera.');
assert(html.includes('id="desktopContactBtn"')&&html.includes('class="lobbyContact"'),'Escritorio debe tener CONTACTANOS debajo de Crear Mesa.');
assert(html.includes('id="contactPhoneNumber"'),'El panel debe mostrar el número de contacto.');
assert(html.includes('id="groupBtn"')&&html.includes('UNIRME AL GRUPO / CANAL'),'El panel debe tener grupo/canal.');
assert(html.includes('id="collaborationBox"')&&html.includes('COLABORÁ PARA SEGUIR CRECIENDO'),'El panel debe tener colaboración.');
assert(community.includes("state.whatsapp?.collaborationAlias"),'Community JS debe leer el alias de colaboración.');
assert(community.includes("$('mobileContactBtn').onclick=openWhatsapp")&&community.includes("$('desktopContactBtn').onclick=openWhatsapp"),'Ambos CONTACTANOS deben abrir el panel existente.');
assert(adminHtml.includes('id="communityCollaborationAlias"'),'Admin debe permitir configurar colaboración por alias.');
assert(adminHtml.includes('LINK DEL GRUPO O CANAL DE WHATSAPP'),'Admin debe identificar grupo o canal.');
assert(admin.includes('collaborationAlias:')&&admin.includes('collaborationHolder:'),'Admin debe guardar alias y titular.');
assert(server.includes('collaborationAlias: String(process.env.COMMUNITY_COLLABORATION_ALIAS'),'Servidor debe tener alias persistente de colaboración.');
assert(server.includes('function communityCollaborationAlias()'),'Servidor debe publicar solo alias de colaboración válidos.');
assert(server.includes('collaborationAlias: communityCollaborationAlias()'),'Estado público debe incluir alias de colaboración.');
assert(html.includes('/js/community.js?v=solo-community-20260828'),'Community debe conservar caché versionada.');
assert(adminHtml.includes('js/admin.js?v=v9-3-12-alias-colabora-20260825'),'Debe invalidarse caché de Admin para V9.3.12.');
console.log('OK CONTACTANOS + colaboración por alias');
